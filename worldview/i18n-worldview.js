(function () {
  'use strict';
  var STORAGE_KEY = 'ming-lang';
  var EN = window.MING_EN || {};

  function getLang() {
    try { return localStorage.getItem(STORAGE_KEY) || 'zh'; } catch (e) { return 'zh'; }
  }

  function applyLang(lang) {
    var isEn = lang === 'en';
    document.documentElement.lang = isEn ? 'en' : 'zh-CN';

    var nodes = document.querySelectorAll('[data-i18n]');
    for (var i = 0; i < nodes.length; i++) {
      var el = nodes[i];
      var key = el.getAttribute('data-i18n');
      if (isEn) {
        var en = EN[key];
        if (en != null) el.textContent = en;
      } else if (el.dataset.i18nZh != null) {
        el.textContent = el.dataset.i18nZh;
      }
    }

    var htmlNodes = document.querySelectorAll('[data-i18n-html]');
    for (var j = 0; j < htmlNodes.length; j++) {
      var hel = htmlNodes[j];
      var hkey = hel.getAttribute('data-i18n-html');
      if (isEn) {
        var hen = EN[hkey];
        if (hen != null) hel.innerHTML = hen;
      } else if (hel.dataset.i18nZhHtml != null) {
        hel.innerHTML = hel.dataset.i18nZhHtml;
      }
    }

    var btns = document.querySelectorAll('.lang-switch');
    for (var k = 0; k < btns.length; k++) {
      btns[k].classList.toggle('active', btns[k].getAttribute('data-lang') === lang);
    }

    try { localStorage.setItem(STORAGE_KEY, lang); } catch (e) {}
  }

  function toggle() { applyLang(getLang() === 'zh' ? 'en' : 'zh'); }

  document.addEventListener('DOMContentLoaded', function () {
    var n = document.querySelectorAll('[data-i18n]');
    for (var i = 0; i < n.length; i++) {
      if (n[i].dataset.i18nZh == null) n[i].dataset.i18nZh = n[i].textContent;
    }
    var h = document.querySelectorAll('[data-i18n-html]');
    for (var j = 0; j < h.length; j++) {
      if (h[j].dataset.i18nZhHtml == null) h[j].dataset.i18nZhHtml = h[j].innerHTML;
    }
    var btns = document.querySelectorAll('.lang-switch');
    for (var k = 0; k < btns.length; k++) {
      (function (btn) {
        btn.addEventListener('click', function () {
          var t = btn.getAttribute('data-lang');
          applyLang(t || (getLang() === 'zh' ? 'en' : 'zh'));
        });
      })(btns[k]);
    }
    applyLang(getLang());
  });

  window.MING_I18N = { applyLang: applyLang, toggle: toggle, getLang: getLang };
})();
